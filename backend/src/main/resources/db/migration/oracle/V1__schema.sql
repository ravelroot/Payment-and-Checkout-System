CREATE TABLE vl_user (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(120 CHAR) NOT NULL,
    email VARCHAR2(160 CHAR) NOT NULL,
    password_hash VARCHAR2(100 CHAR) NOT NULL,
    user_role VARCHAR2(20 CHAR) NOT NULL,
    phone VARCHAR2(30 CHAR),
    document VARCHAR2(20 CHAR),
    active NUMBER(1) NOT NULL,
    failed_logins NUMBER(10) NOT NULL,
    locked_until TIMESTAMP(6),
    last_login_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_user_email UNIQUE (email)
);

CREATE TABLE vl_session (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    token_hash VARCHAR2(64 CHAR) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    last_seen_at TIMESTAMP(6) NOT NULL,
    ended_at TIMESTAMP(6),
    end_reason VARCHAR2(20 CHAR),
    ip_address VARCHAR2(45 CHAR),
    user_agent VARCHAR2(255 CHAR),
    CONSTRAINT uk_session_token_hash UNIQUE (token_hash)
);

